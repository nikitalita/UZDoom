inline string PathToUri(const string& p) {
  if (p.empty()) {
    return p;
  }
  string path = p;
  std::transform(path.begin(), path.end(), path.begin(), [](char c) {
    if (c == '\\') {
      return '/';
    }
    return c;
  });
  return "file://" + path;
}

inline string UriToPath(const string& uri) {
  if (uri.empty()) {
    return uri;
  }
  std::string path;
  for (char c : uri) {
    if ((c >= 'a' && c <= 'z') || (c >= 'A' && c <= 'Z') ||
        (c >= '0' && c <= '9') || c == '+' || c == '/' || c == ':' ||
        c == '.' || c == '-' || c == '_' || c == '~' || c > '\xFF') {
      path += c;
    } else if (c == '\\') {
      path += '/';
    } else {
      path += "%" + std::to_string(static_cast<int>(c));
    }
  }
  return path;
}

