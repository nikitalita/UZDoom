inline bool IsConversionNecessary(const InitializeRequest& clientCaps,
                                  const ServerCaps& serverCaps) {
  if (!serverCaps.convertSourcePaths && !serverCaps.convertSourceOrigins &&
      !serverCaps.convertLines && !serverCaps.convertColumns) {
    return false;
  }
  if ((serverCaps.pathsAreURIs ==
       (clientCaps.pathFormat.value("path") == "uri")) &&
      (serverCaps.linesStartAt1 == clientCaps.linesStartAt1.value(true)) &&
      (serverCaps.columnsStartAt1 == clientCaps.columnsStartAt1.value(true))) {
    return false;
  }
  return true;
}

template <typename T>
struct response_converter<ResponseOrError<T>, traits::EnableIfIsType<ResponseOrError<T>, T>>{
	void convert(ResponseOrError<T>& obj,
		const InitializeRequest& clientCaps,
		const ServerCaps& serverCaps) {
			if (obj.error.has_value()){
				return;
			}
			response_converter<T>{}.convert(obj.response, clientCaps, serverCaps);
	}
};

template <typename T>
void ConvertRequestToServer(T& obj,
                            const InitializeRequest& clientCaps,
                            const ServerCaps& serverCaps) {
  if (!IsConversionNecessary(clientCaps, serverCaps)) {
    return;
  }
  request_converter<T> converter;
  converter.convert(obj, clientCaps, serverCaps);
}

