inline StackFrame ConvertStackFrameToClient(StackFrame& stackFrame,
                                            const InitializeRequest& clientCaps,
                                            const ServerCaps& caps) {
  if (stackFrame.source.has_value() &&
      (caps.convertSourcePaths || caps.convertSourceOrigins)) {
    ConvertSourceToClient(stackFrame.source.value(), clientCaps, caps);
  }
  /* special handling for non-optional line and column; due to the ambiguity of
  the spec regarding this:
          // The line within the source of the frame. If the source attribute is
  missing
          // or doesn't exist, 'line' is 0 and should be ignored by the client.
  We only convert it if the source exists */
  if (caps.convertStackFrameLineAndColumnWhenSourceDoesntExist ||
      (stackFrame.source.has_value())) {
    if (caps.convertLines) {
      stackFrame.line = ConvertLineToServer(stackFrame.line, clientCaps, caps);
    }
    if (caps.convertColumns) {
      stackFrame.column =
          ConvertColumnToServer(stackFrame.column, clientCaps, caps);
    }
  }
  if (stackFrame.endColumn.has_value() && caps.convertColumns) {
    stackFrame.endColumn =
        ConvertColumnToServer(stackFrame.endColumn.value(), clientCaps, caps);
  }
  if (stackFrame.endLine.has_value() && caps.convertLines) {
    stackFrame.endLine =
        ConvertLineToServer(stackFrame.endLine.value(), clientCaps, caps);
  }
  return stackFrame;
}
